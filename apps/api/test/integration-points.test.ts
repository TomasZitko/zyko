/**
 * Proves the reserved integration points are pluggable without platform changes:
 * a design engine and a chat provider are swapped in at runtime and driven through the normal flows.
 */
import { afterAll, describe, expect, it } from "vitest";
import { newNodeId, notConfiguredDesignEngine, type DesignEngine } from "@zyko/contracts";
import { registerDesignEngine, designRegistry } from "../src/registry.js";
import { setProvider } from "../src/ai/orchestrator.js";
import { mockProvider } from "../src/ai/mock.js";
import { toWire } from "../src/ai/anthropic.js";
import type { ChatProvider } from "../src/ai/provider.js";
import { setupProject } from "./helpers.js";

afterAll(() => { registerDesignEngine(notConfiguredDesignEngine); setProvider(mockProvider); });

/** TEST-ONLY engine: emits fixed fixture nodes. It demonstrates the contract, not a design algorithm. */
const fixtureEngine = (bad = false): DesignEngine => ({
  id: "test-fixture-engine", version: "0.0.1", available: true,
  async analyzeRequirements(input) { return { summary: input.project.name, pages: [{ path: "/", title: "Home", purpose: "landing" }, { path: "/contact", title: "Contact", purpose: "contact" }], missingInformation: [] }; },
  async createPlan(input, a) { return { designSystem: { id: input.designSystem.id, version: input.designSystem.version }, pages: a.pages.map((p) => ({ path: p.path, title: p.title, sections: [{ component: "section", intent: p.purpose }] })) }; },
  async generate(input, plan) {
    return {
      pages: plan.pages.map((p) => {
        const sec = input.registry.createNode(input.designSystem.id, input.designSystem.version, "section", newNodeId());
        sec.slots!.default.push(input.registry.createNode(input.designSystem.id, input.designSystem.version, bad ? "heading-that-does-not-exist" as any : "heading", newNodeId(), { text: `${p.title} — ${input.project.brief.description ?? ""}`, level: "h1" }));
        return { path: p.path, title: p.title, document: { schemaVersion: 1 as const, root: [sec] } };
      }),
      explanation: "fixture output",
    };
  },
});

const approve = async (c: any, convId: string, text: string) => {
  const r = await c.post(`/api/conversations/${convId}/messages`, { text });
  const line = r.text.split("\n").find((l: string) => l.startsWith("data:") && l.includes("approval_required"));
  return c.post(`/api/ai-tasks/${JSON.parse(line.slice(5)).taskId}/approve`);
};

describe("design engine integration point", () => {
  it("applies validated engine output as AI draft revisions after approval", async () => {
    registerDesignEngine(fixtureEngine());
    const { c, project } = await setupProject("Engine");
    const conv = (await c.post(`/api/projects/${project.id}/conversations`, {})).json.conversation;
    const d = await approve(c, conv.id, '/tool request_design_generation {"stage":"generate"}');
    expect(d.json.task.status).toBe("succeeded");
    expect(d.json.outcome.result.applied.map((x: any) => x.path)).toEqual(["/", "/contact"]);
    const pages = (await c.get(`/api/projects/${project.id}/pages`)).json.pages;
    expect(pages.map((p: any) => p.path).sort()).toEqual(["/", "/contact"]);
    const home = (await c.get(`/api/pages/${pages.find((p: any) => p.path === "/").id}`)).json.page;
    expect(JSON.stringify(home.document)).toContain("A neighbourhood bakery");
    const revs = (await c.get(`/api/pages/${home.id}/revisions`)).json.revisions;
    expect(revs[0]).toMatchObject({ source: "ai", message: "Generated by test-fixture-engine" });
  });

  it("rejects invalid engine output without touching data", async () => {
    expect(() => designRegistry.createNode("fixture-neutral", "0.1.0", "nope", "abcd1234")).toThrow();
    registerDesignEngine({ ...fixtureEngine(), generate: async () => ({ pages: [{ path: "/", title: "X", document: { schemaVersion: 1, root: [{ id: "bad00001", type: "nope", v: 1, props: {} }] } }] }) });
    const { c, project } = await setupProject("EngineBad");
    const conv = (await c.post(`/api/projects/${project.id}/conversations`, {})).json.conversation;
    const before = (await c.get(`/api/projects/${project.id}/pages`)).json.pages[0];
    const d = await approve(c, conv.id, '/tool request_design_generation {"stage":"generate"}');
    expect(d.json.task.status).toBe("failed");
    expect(d.json.task.error).toContain("invalid page");
    expect((await c.get(`/api/pages/${before.id}`)).json.page.version).toBe(before.version);
  });
});

describe("chat provider integration point", () => {
  it("retries transient provider failures and records usage", async () => {
    let calls = 0;
    const flaky: ChatProvider = {
      id: "flaky", model: "flaky-1",
      async stream(req, onText) {
        calls++;
        if (calls === 1) { const { ProviderError } = await import("../src/ai/provider.js"); throw new ProviderError("overloaded", true, 529); }
        return mockProvider.stream(req, onText);
      },
    };
    setProvider(flaky);
    const { c, project } = await setupProject("Flaky");
    const conv = (await c.post(`/api/projects/${project.id}/conversations`, {})).json.conversation;
    const r = await c.post(`/api/conversations/${conv.id}/messages`, { text: "hello" });
    expect(r.text).toContain("event: done");
    expect(calls).toBe(2);
    setProvider(mockProvider);
  });

  it("surfaces non-retryable provider errors to the user and persists an error message", async () => {
    const { ProviderError } = await import("../src/ai/provider.js");
    setProvider({ id: "down", model: "x", stream: async () => { throw new ProviderError("bad request", false, 400); } });
    const { c, project } = await setupProject("Down");
    const conv = (await c.post(`/api/projects/${project.id}/conversations`, {})).json.conversation;
    const r = await c.post(`/api/conversations/${conv.id}/messages`, { text: "hello" });
    expect(r.text).toContain("event: error");
    const msgs = (await c.get(`/api/conversations/${conv.id}`)).json.messages;
    expect(msgs.at(-1)).toMatchObject({ role: "assistant", status: "error" });
    setProvider(mockProvider);
  });

  it("translates neutral history to the Claude wire format (tool pairs, merged turns, raw replay)", () => {
    const wire = toWire([
      { role: "user", content: [{ type: "text", text: "hi" }] },
      { role: "assistant", content: [{ type: "text", text: "calling" }, { type: "tool_use", id: "t1", name: "inspect_page", input: { path: "/" } }, { type: "raw", provider: "anthropic", model: "m", content: [{ type: "thinking", thinking: "", signature: "sig" }, { type: "tool_use", id: "t1", name: "inspect_page", input: { path: "/" } }] }] },
      { role: "user", content: [{ type: "tool_result", toolUseId: "t1", content: "{}" }] },
      { role: "user", content: [{ type: "text", text: "[platform] approved" }] },
    ], "m");
    expect(wire).toHaveLength(3);
    expect((wire[1].content as any[])[0].type).toBe("thinking"); // replayed unchanged
    expect((wire[2].content as any[]).map((b) => b.type)).toEqual(["tool_result", "text"]);
  });
});
