import {
  SafeHtml, escapeHtml, html, mergeTokens, safeUrl, tokensToCss, unsafeRaw,
  type DesignRegistry, type DesignSystemManifest, type PageDocument, type PageNode, type RenderContext,
  type RenderTarget, type ResolvedAsset, type SiteSettings, type PageSeo,
} from "@zyko/contracts";

export interface RenderOptions {
  registry: DesignRegistry;
  designSystem: { id: string; version: string };
  target: RenderTarget;
  site: SiteSettings;
  pages: { path: string; title: string }[];
  resolveAsset: (id: string) => ResolvedAsset | null;
}

export interface RenderedPage {
  body: string;
  css: string;
  /** Component types used on the page (for diagnostics / caching). */
  types: string[];
}

const COLOR_RE = /^#[0-9a-f]{3,8}$/i;

/** Renders a page document to HTML + CSS. Pure; runs in Node (publishing) and the browser (editor). */
export function renderDocument(doc: PageDocument, opts: RenderOptions): RenderedPage {
  const { registry, designSystem } = opts;
  const manifest = registry.get(designSystem.id, designSystem.version);
  const migrated = registry.migrateDocument(designSystem.id, designSystem.version, doc);
  const used = new Set<string>();

  const renderNodes = (nodes: PageNode[]): SafeHtml => new SafeHtml(nodes.map(renderNode).join(""));

  const renderNode = (node: PageNode): string => {
    const def = registry.component(designSystem.id, designSystem.version, node.type);
    if (!def) {
      return opts.target === "editor"
        ? html`<div data-zyko-node="${node.id}" class="zy-missing">Unknown component: ${node.type}</div>`.value
        : "";
    }
    used.add(node.type);
    const ctx: RenderContext = {
      target: opts.target,
      nodeId: node.id,
      site: { name: opts.site.name, locale: opts.site.locale, pages: opts.pages },
      slot: (name = "default") => renderNodes(node.slots?.[name] ?? []),
      asset: (id) => (id ? opts.resolveAsset(id) : null),
      link: (href) => safeUrl(href),
      token: (group, name) => `var(--zy-${group === "fontSize" ? "font-size" : group}-${name.replace(/[^a-z0-9-]/g, "")})`,
      color: (v) => {
        const s = String(v ?? "");
        if (s.startsWith("token:")) return `var(--zy-color-${s.slice(6).replace(/[^a-z0-9-]/g, "")})`;
        return COLOR_RE.test(s) ? s : "inherit";
      },
      editable: (prop) => (opts.target === "editor" ? unsafeRaw(` data-zyko-prop="${escapeHtml(prop)}"`) : unsafeRaw("")),
    };
    const props = { ...def.defaultProps, ...node.props };
    let out: string;
    try {
      out = def.render(props, ctx).value;
    } catch (err) {
      out = opts.target === "editor" ? html`<div class="zy-missing">Render error in ${node.type}: ${(err as Error).message}</div>`.value : "";
    }
    const hide = node.layout?.hideOn ?? [];
    const hideCls = hide.map((b) => `zy-hide-${b}`).join(" ");
    if (opts.target === "editor") {
      return `<div data-zyko-node="${escapeHtml(node.id)}" data-zyko-type="${escapeHtml(node.type)}" class="zy-node ${hideCls}" style="display:contents">${out}</div>`;
    }
    return hide.length ? `<div class="${hideCls}" style="display:contents">${out}</div>` : out;
  };

  const body = renderNodes(migrated.root).value;
  const { tablet, desktop } = manifest.breakpoints;
  const responsive =
    `@media (max-width:${tablet - 1}px){.zy-hide-mobile{display:none!important}}` +
    `@media (min-width:${tablet}px) and (max-width:${desktop - 1}px){.zy-hide-tablet{display:none!important}}` +
    `@media (min-width:${desktop}px){.zy-hide-desktop{display:none!important}}`;
  const componentCss = manifest.components.filter((c) => used.has(c.type) && c.css).map((c) => c.css).join("\n");
  const css = [tokensToCss(mergeTokens(manifest.tokens, opts.site.tokenOverrides as any)), manifest.baseCss, componentCss, responsive].join("\n");
  return { body, css, types: [...used] };
}

export interface HtmlDocumentOptions {
  rendered: RenderedPage;
  site: SiteSettings;
  page: { path: string; title: string; seo: PageSeo };
  canonicalBase?: string | null;
  ogImageUrl?: string | null;
  /** Extra trusted head/body markup generated by the platform (analytics beacon, editor bridge). */
  headExtra?: string;
  bodyExtra?: string;
  forceNoindex?: boolean;
}

export function renderHtmlDocument(o: HtmlDocumentOptions): string {
  const { site, page } = o;
  const titleText = page.seo.title || (site.seo?.titleTemplate ?? "%s").replace("%s", page.title);
  const description = page.seo.description || site.seo?.description || "";
  const canonical = page.seo.canonical || (o.canonicalBase ? o.canonicalBase.replace(/\/$/, "") + page.path : null);
  const noindex = o.forceNoindex || page.seo.noindex;
  return `<!doctype html>
<html lang="${escapeHtml(site.locale)}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(titleText)}</title>
${description ? `<meta name="description" content="${escapeHtml(description)}">` : ""}
${canonical ? `<link rel="canonical" href="${escapeHtml(canonical)}">` : ""}
${noindex ? `<meta name="robots" content="noindex, nofollow">` : ""}
<meta property="og:title" content="${escapeHtml(titleText)}">
${description ? `<meta property="og:description" content="${escapeHtml(description)}">` : ""}
${o.ogImageUrl ? `<meta property="og:image" content="${escapeHtml(o.ogImageUrl)}">` : ""}
<meta name="generator" content="zyko">
<style>${o.rendered.css.replace(/<\/style/gi, "<\\/style")}</style>
${o.headExtra ?? ""}
</head>
<body>
${o.rendered.body}
${o.bodyExtra ?? ""}
</body>
</html>`;
}

export function buildSitemap(baseUrl: string, pages: { path: string; updatedAt: Date | string; noindex?: boolean }[]): string {
  const base = baseUrl.replace(/\/$/, "");
  const urls = pages
    .filter((p) => !p.noindex)
    .map((p) => `<url><loc>${escapeHtml(base + p.path)}</loc><lastmod>${new Date(p.updatedAt).toISOString()}</lastmod></url>`)
    .join("");
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">${urls}</urlset>\n`;
}

export function buildRobots(baseUrl: string | null, allowIndexing: boolean): string {
  if (!allowIndexing) return "User-agent: *\nDisallow: /\n";
  return `User-agent: *\nAllow: /\n${baseUrl ? `Sitemap: ${baseUrl.replace(/\/$/, "")}/sitemap.xml\n` : ""}`;
}

/** SEO readiness checks used by the publish screen. */
export function seoIssues(site: SiteSettings, pages: { path: string; title: string; seo: PageSeo }[]): { path: string; level: "error" | "warning"; message: string }[] {
  const out: { path: string; level: "error" | "warning"; message: string }[] = [];
  const titles = new Map<string, string>();
  if (!pages.some((p) => p.path === "/")) out.push({ path: "/", level: "error", message: "Site has no home page (/)" });
  for (const p of pages) {
    const t = p.seo.title || p.title;
    if (!t) out.push({ path: p.path, level: "error", message: "Missing title" });
    if (titles.has(t)) out.push({ path: p.path, level: "warning", message: `Duplicate title with ${titles.get(t)}` });
    titles.set(t, p.path);
    if (!p.seo.description && !site.seo?.description) out.push({ path: p.path, level: "warning", message: "Missing meta description" });
  }
  return out;
}

